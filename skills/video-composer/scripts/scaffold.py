SRC_SCENE = """\
import React from 'react';
import {
  AbsoluteFill,
  Audio,
  Img,
  OffthreadVideo,
  Sequence,
  interpolate,
  useCurrentFrame,
} from 'remotion';
import type { Scene } from './types';
import { resolveSrc } from './utils';

const Captions: React.FC<{ scene: Scene }> = ({ scene }) => {
  const frame = useCurrentFrame();
  const captions = scene.captions ?? [];
  return (
    <>
      {captions.map((c, i) => {
        const from = c.fromFrame ?? 0;
        const to = c.toFrame ?? scene.durationInFrames;
        if (frame < from || frame > to) return null;
        const pos = c.position ?? 'bottom';
        const justify =
          pos === 'top' ? 'flex-start' : pos === 'center' ? 'center' : 'flex-end';
        const opacity = interpolate(
          frame,
          [from, from + 8, to - 8, to],
          [0, 1, 1, 0],
          { extrapolateLeft: 'clamp', extrapolateRight: 'clamp' }
        );
        return (
          <AbsoluteFill
            key={i}
            style={{ justifyContent: justify, alignItems: 'center', padding: '6%' }}
          >
            <div
              style={{
                opacity,
                maxWidth: '88%',
                textAlign: 'center',
                fontFamily: 'sans-serif',
                fontWeight: 700,
                fontSize: 64,
                lineHeight: 1.25,
                color: 'white',
                textShadow: '0 2px 12px rgba(0,0,0,0.85)',
                background: 'rgba(0,0,0,0.35)',
                padding: '18px 36px',
                borderRadius: 18,
              }}
            >
              {c.text}
            </div>
          </AbsoluteFill>
        );
      })}
    </>
  );
};

const Backdrop: React.FC<{ scene: Scene }> = ({ scene }) => {
  const frame = useCurrentFrame();
  const media = scene.media;
  if (!media) {
    return <AbsoluteFill style={{ backgroundColor: '#101418' }} />;
  }
  const fit = media.fit ?? 'cover';
  const src = resolveSrc(media.src);

  // Ken Burns: slow zoom + drift for still images.
  const scale = scene.kenBurns
    ? interpolate(frame, [0, scene.durationInFrames], [1, 1.08], {
        extrapolateRight: 'clamp',
      })
    : 1;
  const translateY = scene.kenBurns
    ? interpolate(frame, [0, scene.durationInFrames], [0, -20], {
        extrapolateRight: 'clamp',
      })
    : 0;

  const style: React.CSSProperties = {
    width: '100%',
    height: '100%',
    objectFit: fit,
    transform: `scale(${scale}) translateY(${translateY}px)`,
  };

  return (
    <AbsoluteFill style={{ backgroundColor: 'black' }}>
      {media.type === 'video' ? (
        <OffthreadVideo src={src} style={style} muted={false} />
      ) : (
        <Img src={src} style={style} />
      )}
    </AbsoluteFill>
  );
};

export const SceneView: React.FC<{ scene: Scene }> = ({ scene }) => {
  const vo = scene.voiceover;
  return (
    <AbsoluteFill>
      <Backdrop scene={scene} />
      <Captions scene={scene} />
      {vo ? (
        <Sequence from={vo.delayInFrames ?? 0}>
          <Audio src={resolveSrc(vo.src)} volume={vo.volume ?? 1} />
        </Sequence>
      ) : null}
    </AbsoluteFill>
  );
};
"""

SRC_VIDEO = """\
import React from 'react';
import { AbsoluteFill, Audio } from 'remotion';
import { TransitionSeries, linearTiming } from '@remotion/transitions';
import { fade } from '@remotion/transitions/fade';
import { slide } from '@remotion/transitions/slide';
import { wipe } from '@remotion/transitions/wipe';
import type { Scene, VideoProps } from './types';
import { resolveSrc, transitionFrames } from './utils';
import { SceneView } from './Scene';

const presentationFor = (scene: Scene) => {
  const t = scene.transitionToNext;
  const dir = (t?.direction ?? 'from-right') as any;
  switch (t?.type) {
    case 'slide':
      return slide({ direction: dir });
    case 'wipe':
      return wipe({ direction: dir });
    case 'fade':
    default:
      return fade();
  }
};

export const Video: React.FC<VideoProps> = (props) => {
  const scenes = props.scenes ?? [];
  return (
    <AbsoluteFill style={{ backgroundColor: 'black' }}>
      <TransitionSeries>
        {scenes.map((scene, i) => {
          const elements: React.ReactNode[] = [
            <TransitionSeries.Sequence
              key={`s-${i}`}
              durationInFrames={Math.max(1, scene.durationInFrames)}
            >
              <SceneView scene={scene} />
            </TransitionSeries.Sequence>,
          ];
          const tf = transitionFrames(scene);
          if (i < scenes.length - 1 && tf > 0) {
            elements.push(
              <TransitionSeries.Transition
                key={`t-${i}`}
                presentation={presentationFor(scene)}
                timing={linearTiming({ durationInFrames: tf })}
              />
            );
          }
          return elements;
        })}
      </TransitionSeries>

      {props.bgm ? (
        <Audio src={resolveSrc(props.bgm.src)} volume={props.bgm.volume ?? 0.25} loop />
      ) : null}
    </AbsoluteFill>
  );
};
"""

