# Asset sub-directories created under public/.
PUBLIC_DIRS = ["public/images", "public/video", "public/audio"]


def main() -> None:
    parser = argparse.ArgumentParser(description="Scaffold a Remotion project for video-composer")
    parser.add_argument("project_dir", help="Target project directory")
    parser.add_argument("--force", action="store_true", help="Overwrite existing files")
    args = parser.parse_args()

    root = Path(args.project_dir).expanduser()
    root.mkdir(parents=True, exist_ok=True)

    written = []
    skipped = []
    for rel, content in FILES.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and not args.force:
            skipped.append(rel)
            continue
        target.write_text(content, encoding="utf-8")
        written.append(rel)

    for d in PUBLIC_DIRS:
        (root / d).mkdir(parents=True, exist_ok=True)
        gk = root / d / ".gitkeep"
        if not gk.exists():
            gk.write_text("", encoding="utf-8")

    print(f"Scaffolded Remotion project at: {root}")
    if written:
        print("  wrote:   " + ", ".join(written))
    if skipped:
        print("  skipped (exists): " + ", ".join(skipped))
    print("\nNext steps:")
    print(f"  1) Generate assets into {root}/public/{{images,video,audio}}/")
    print(f"  2) Copy props.sample.json -> props.json and edit the timeline")
    print(f"  3) python scripts/render_video.py --project {root} --props {root}/props.json --install")


if __name__ == "__main__":
    main()
